"""Public database API — a facade over the focused modules in `src/db/`.

Everything the rest of the service (and the test suite) imports as
`src.database` is re-exported here, so `from src import database` keeps working
while the implementation lives in one module per domain:

    src/db/core.py        connection() and the query helpers
    src/db/schema.py      the canonical DDL
    src/db/migrations/    the registry, the steps and the runner
    src/db/admin.py       init_db, backup/restore, wait_for_schema_ready
    src/db/jobs.py        jobs, chat state, thumbnails, document outputs
    src/db/users.py       users, identities, per-chat settings and domains
    src/db/tags.py        tags, tag links and job annotations
    src/db/spaces.py      spaces, pinned jobs and context blobs
    src/db/newsletter.py  watches, publications, issues and digest candidates
    src/db/templates.py   user-defined prompt templates
    src/db/cache.py       the Jina markdown cache

Add new functions to the module that owns the table, not to this file — this is
an export list, not a home for logic.
"""

